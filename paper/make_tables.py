"""Q10: regenerate every paper table from the CSVs as LaTeX (booktabs, needs graphicx for \\resizebox) in paper/tables/*.tex. Missing inputs give a table
with a "pending: <run>" row, so the command always succeeds.
  T1 tab_lqr              Part 1 LQR failed / catastrophic per family and controller, 95 % seed-bootstrap CI (out/stats)
  T2 tab_swap             LQR swap test, LN MSE 3000 (out/stats/swap_rates_boot.csv)
  T3 tab_dpc_arch         DPC failed / trapped of 30 per family: GRU, MLP, linear, GRU B = 0.1, held-out (Run 8), RMSNorm (Run 9)
  T4 tab_lambda_confusion confusion matrices of the Lambda* predictions (GRU retrospective, MLP, linear, B = 0.1 direct and aug)
  T5 tab_optimiser        Task 3.5 table (out/opt/from_scratch.csv; pending until Run 4 is complete)
  T6 tab_b01              B = 0.01 vs B = 0.1: fixed-LQR failed and DPC trapped per family (out/B01/report)
  T7 tab_heldout          held-out seeds 10-29, Part 1 replication against the pre-registered intervals (pending)
  T8 tab_rms              RMSNorm kink and LQR (pending)
python paper/make_tables.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..")); sys.path.insert(0, os.path.join(HERE, "..", "analysis"))
import paths  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

OUT = os.path.join(HERE, "tables")
R = lambda *a: os.path.join(paths.REPO, *a)
FAM = ["LN MSE 3000", "LN MSE 12000", "LN slope from 0", "LN two-stage", "no norm", "static norm"]
LQRF = {"LN slope from 0": "LN slope from step 0"}


def tex(name, cols, rows, caption):
    os.makedirs(OUT, exist_ok=True)
    spec = "l" + "r" * (len(cols) - 1)
    esc = lambda c: str(c) if ("$" in str(c) or "\\" in str(c)) else str(c).replace("_", "\\_").replace("%", "\\%")
    body = "\n".join(" & ".join(esc(c) for c in r) + r" \\" for r in rows)
    s = (f"% generated by paper/make_tables.py\n\\begin{{table}}[t]\\centering\\small\n\\caption{{{caption}}}\\label{{tab:{name}}}\n"
         f"\\resizebox{{\\linewidth}}{{!}}{{\\begin{{tabular}}{{{spec}}}\\toprule\n{' & '.join(cols)} \\\\\\midrule\n{body}\n\\bottomrule\\end{{tabular}}}}\n\\end{{table}}\n")
    open(os.path.join(OUT, f"{name}.tex"), "w").write(s)
    print("wrote", name)


def pending(name, cols, what, caption):
    tex(name, cols, [[f"\\multicolumn{{{len(cols)}}}{{c}}{{pending: {what.replace('_', '\\_')}}}"]], caption)


def ci(r):
    return f"{r.pct:.1f} [{r.ci_lo:.1f}, {r.ci_hi:.1f}]"


def t1():
    fn = R("out", "stats", "lqr_rates_boot.csv"); cols = ["family", "fixed failed", "fixed catastrophic", "resched. failed", "resched. catastrophic"]
    if not os.path.exists(fn):
        return pending("tab_lqr", cols, "analysis/stats.py", "LQR failure rates.")
    T = pd.read_csv(fn).set_index(["family", "controller", "metric"])
    rows = [[f] + [ci(T.loc[(LQRF.get(f, f), c, m)]) for c in ("LQR fixed", "LQR sched") for m in ("failed", "catastrophic")] for f in FAM]
    tex("tab_lqr", cols, rows, "Fixed and rescheduled LQR on the true plant, per surrogate family: \\% of runs failed (gap $>10\\%$ or diverged) and catastrophic (gap $>100\\%$ or diverged), runs with $|x_0-r|\\ge0.5$ (880 per cell), 95\\% seed-bootstrap intervals.")


def t2():
    fn = R("out", "stats", "swap_rates_boot.csv"); cols = ["slopes used by the LQR design", "failed (\\%)", "catastrophic (\\%)"]
    if not os.path.exists(fn):
        return pending("tab_swap", cols, "swap test", "Swap test.")
    T = pd.read_csv(fn); T = T[T.family == "LN MSE 3000"]
    rows = [[d, ci(g[g.metric == "failed"].iloc[0]), ci(g[g.metric == "catastrophic"].iloc[0])] for d, g in T.groupby("design", sort=False)]
    tex("tab_swap", cols, rows, "Swap test, fixed LQR on LN MSE 3000 surrogates: replacing the surrogate's state or input slope at the setpoint by the true value.")


SETS = [("GRU", R("data", "dpc_out")), ("MLP", R("data", "run5_mlp")), ("linear", R("data", "run5_linear")),
        ("GRU, $B=0.1$", R("data", "run6_B01")), ("GRU, seeds 10--29", R("data", "run8_s10_29")), ("GRU, RMSNorm", R("data", "run9_rms"))]


def t3():
    from common import runs, FAMILY
    cols = ["family"] + [s for s, _ in SETS]
    cnt = {}
    for s, root in SETS:
        if os.path.exists(os.path.join(root, "dpc_results.csv")) and os.path.exists(os.path.join(root, "dpc_diag.csv")):
            Rr = runs(root); Rr = Rr[Rr.model.isin(FAMILY)].assign(family=lambda d: d.model.map(FAMILY))
            cnt[s] = Rr.groupby("family").agg(f=("failed", "sum"), t=("trapped", "sum"), n=("failed", "size"))
    rows = []
    for f in FAM:
        rows.append([f] + [(f"{int(cnt[s].loc[f, 't'])} / {int(cnt[s].loc[f, 'f'])}" if s in cnt and f in cnt[s].index else "pending")
                           for s, _ in SETS])
    tex("tab_dpc_arch", cols, rows, "DPC through the surrogates: trapped / failed runs of 30 (10 seeds $\\times$ 3 repeats) per family and controller architecture; failed = typical-start gap $>10\\%$, trapped = failed and own controller $>1.05\\times$ the oracle controller through the same surrogate.")


def t4():
    from common import runs, FAMILY
    specs = [("GRU, $B=0.01$ (retrospective)", R("data", "dpc_out"), R("out", "theory", "t2_runs_all_B001.csv"), "S_seg_max", None, 12.1),
             ("MLP (prospective)", R("data", "run5_mlp"), R("prereg", "PREREG_arch_predicted.csv"), "Lambda_star", "mlp", 12.1),
             ("linear (prospective)", R("data", "run5_linear"), R("prereg", "PREREG_arch_predicted.csv"), "Lambda_star", "linear", 12.1),
             ("GRU, $B=0.1$, direct (prospective)", R("data", "run6_B01"), R("prereg", "PREREG_B01_predicted.csv"), "S_seg_max", None, 12.1),
             ("GRU, $B=0.1$, augmented (prospective)", R("data", "run6_B01"), R("prereg", "PREREG_B01_aug_predicted.csv"), "L_aug_star", None, 12.08)]
    cols = ["test", "runs", "trapped", "predicted", "hits", "misses", "false alarms"]
    rows = []
    for name, root, lam, col, arch, thr in specs:
        if not (os.path.exists(os.path.join(root, "dpc_results.csv")) and os.path.exists(lam)):
            rows.append([name] + ["pending"] * 6); continue
        Rr = runs(root); Rr = Rr[Rr.model.isin(FAMILY)].assign(family=lambda d: d.model.map(FAMILY))
        L = pd.read_csv(lam)
        if arch:
            L = L[L.arch == arch]
        J = Rr.merge(L[["family", "seed", "rep", col]], on=["family", "seed", "rep"]); p = J[col] > thr; t = J.trapped
        rows.append([name, len(J), int(t.sum()), int(p.sum()), int((p & t).sum()), int((~p & t).sum()), int((p & ~t).sum())])
    tex("tab_lambda_confusion", cols, rows, "Landing amplification $\\Lambda^\\star$ of the oracle controller as a run-level trap predictor (threshold 12.1; augmented statistic 12.08), retrospective on the GRU at $B=0.01$ and prospective (pre-registered) elsewhere.")


def t5():
    fn = R("out", "opt", "from_scratch.csv"); cols = ["setting", "failed / 30", "trapped / 30", "median gap (\\%)", "best-seed gap (\\%)", "s per seed"]
    T = pd.read_csv(fn) if os.path.exists(fn) else None
    if T is None or (T.runs.fillna(0) < 30).any():
        return pending("tab_optimiser", cols, "Run 4 (re-run analysis/opt_report.py)", "Optimiser baselines from scratch.")
    rows = [[r.setting, int(r.failed), int(r.trapped), f"{r.median_gap_pct:.2f}", f"{r.best_seed_gap_pct:.2f}", f"{r.s_per_seed:.0f}"] for _, r in T.iterrows()]
    tex("tab_optimiser", cols, rows, "Optimiser baselines from scratch, GRU through the LN MSE 3000 surrogates (two-stage with the plain optimiser as reference).")


def t6():
    d = R("out", "B01", "report"); cols = ["family", "fixed LQR failed, $B=0.01$", "$B=0.1$", "DPC trapped, $B=0.01$", "$B=0.1$"]
    if not os.path.exists(os.path.join(d, "dpc_counts.csv")):
        return pending("tab_b01", cols, "Run 6", "B = 0.1.")
    L, D = pd.read_csv(os.path.join(d, "lqr_rates.csv")), pd.read_csv(os.path.join(d, "dpc_counts.csv"))
    g = lambda pl, f: L[(L.plant == pl) & (L.controller == "LQR fixed") & (L.family == f)].failed_pct.iloc[0]
    h = lambda pl, f: int(D[(D.plant == pl) & (D.family == f)].trapped.iloc[0])
    rows = [[f, f"{g('B = 0.01', f):.1f}", f"{g('B = 0.1', f):.1f}", h("B = 0.01", f), h("B = 0.1", f)] for f in FAM]
    tex("tab_b01", cols, rows, "Low ($B=0.01$) and ordinary ($B=0.1$) input authority: fixed-LQR failure rate (\\%) and DPC traps (of 30).")


def t7():
    fn = R("out", "heldout", "outcomes.csv"); cols = ["family", "controller", "metric", "seeds 10--29 (\\%)", "95\\% PI (\\%)", "inside"]
    if not os.path.exists(fn):
        return pending("tab_heldout", cols, "held-out LQR study (Q6c)", "Held-out seeds 10--29.")
    T = pd.read_csv(fn)
    rows = [[r.family, r.controller, r.metric, f"{r.pct:.1f}", f"[{r.pi_lo_pct:.1f}, {r.pi_hi_pct:.1f}]", "yes" if r.inside else "no"] for _, r in T.iterrows()]
    tex("tab_heldout", cols, rows, "Replication of Part 1 on held-out seeds 10--29 against the pre-registered 95\\% prediction intervals.")


def t8():
    fn = R("out", "rms", "summary.csv"); cols = ["family", "median $r^\\star_x$", "median $r^\\star_u$", "fixed LQR failed (\\%)"]
    if not os.path.exists(fn):
        return pending("tab_rms", cols, "RMSNorm surrogates (Q7d)", "RMSNorm surrogates.")
    T = pd.read_csv(fn)
    rows = [[r.family, f"{r.rstar_x:.3f}", f"{r.rstar_u:.3f}", f"{r.fixed_failed_pct:.1f}"] for _, r in T.iterrows()]
    tex("tab_rms", cols, rows, "RMSNorm (no centring) against LayerNorm surrogates: kink half-widths and fixed-LQR failure rate.")


if __name__ == "__main__":
    for f in (t1, t2, t3, t4, t5, t6, t7, t8):
        f()
